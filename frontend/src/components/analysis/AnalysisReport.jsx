function Section({ title, items, render }) {
  if (!items || items.length === 0) {
    return null;
  }
  return (
    <section className="report-section" aria-label={title}>
      <h3>{title}</h3>
      <ul>
        {items.map((item, index) => (
          <li key={index}>{render(item)}</li>
        ))}
      </ul>
    </section>
  );
}

function StructuredReport({ report }) {
  return (
    <>
      <p className="report-headline">{report.headline}</p>
      {report.data_note && <p className="notice report-note">{report.data_note}</p>}

      <Section
        title="✨ Your strengths"
        items={report.strengths}
        render={(s) => (
          <>
            <strong>{s.title}</strong>
            <span className="report-detail">{s.detail}</span>
          </>
        )}
      />

      <Section
        title="🎯 Growth opportunities"
        items={report.growth_opportunities}
        render={(g) => (
          <>
            <strong>{g.area}</strong>
            {(g.current || g.goal) && (
              <span className="report-detail">
                {g.current && g.goal ? `${g.current} → goal: ${g.goal}` : g.current || `Goal: ${g.goal}`}
              </span>
            )}
            <span className="report-detail">Next step: {g.next_step}</span>
          </>
        )}
      />

      <Section
        title="📈 Progress"
        items={report.progress}
        render={(p) => (
          <>
            <strong>{p.metric}</strong>
            <span className="report-detail">{p.before} → {p.after}</span>
          </>
        )}
      />

      <Section
        title="💡 What to know"
        items={report.insights}
        render={(i) => (
          <>
            <strong>{i.title}</strong>
            <span className="report-detail">{i.detail}</span>
          </>
        )}
      />

      {report.closing && <p className="report-closing">💬 {report.closing}</p>}
    </>
  );
}

export default function AnalysisReport({ summary, report, onRunAgain }) {
  return (
    <section className="card report" aria-labelledby="report-title">
      <h2 id="report-title">Analysis complete 🎮</h2>
      {report ? (
        <StructuredReport report={report} />
      ) : (
        <div className="report-body">{summary || 'The analysis finished without a summary.'}</div>
      )}
      <p className="fine-print">
        Generated by an AI. Treat it as a starting point, and compare yourself with
        your past games rather than with anyone else.
      </p>
      <div className="actions">
        <button type="button" className="button ghost" onClick={onRunAgain}>
          Run another analysis
        </button>
      </div>
    </section>
  );
}
